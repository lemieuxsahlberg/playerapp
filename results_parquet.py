def suggest_names(query: str, limit=15):
    """Palauttaa listan parhaita ehdotuksia (ei yhtä 'pakko-osumaa')."""
    q = norm_name(query)
    if not q:
        return []

    # 1) substring-osumat (sukunimi tms.)
