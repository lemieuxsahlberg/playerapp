    subs = subs[:limit]
    if subs:
        return subs

    # 2) fuzzy: käytetään SequenceMatcheria normitetuilla nimillä
    scored = []
    for orig, nrm in name_index:
        score = SequenceMatcher(None, q, nrm).ratio()
        if score >= 0.55:  # tämä raja estää "Matias Röj..." -ankkuroinnin
            scored.append((score, orig))
    scored.sort(reverse=True, key=lambda x: x[0])
    return [orig for score, orig in scored[:limit]]

