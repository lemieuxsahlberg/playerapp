    if status != 200:
        return pd.DataFrame()

    try:
        tables = pd.read_html(StringIO(html))
    except Exception:
        return pd.DataFrame()

    if not tables:
        return pd.DataFrame()

    # Etsi taulu, jossa on eniten rivejä jotka alkaa "numero." (=rank)
    best_i, best_hits = None, 0
    for i, t in enumerate(tables):
        hits = 0
        for col in t.columns:
            s = t[col].astype(str)
            hits = max(hits, s.str.contains(r"^\s*\d{1,3}\.", regex=True, na=False).sum())
        if hits > best_hits:
            best_hits, best_i = hits, i

    # jos ei löydy rank-rivejä, tämä ei ole yksilötulostaulu (tai formaatti poikkeaa täysin)
    if best_i is None or best_hits < 3:
        return pd.DataFrame()

    t = tables[best_i].copy()
    t.columns = [f"c{i}" for i in range(t.shape[1])]

    # etsi sarake jossa rank+nimi on
    rank_col = None
    for c in t.columns:
        if t[c].astype(str).str.contains(r"^\s*\d{1,3}\.", regex=True, na=False).sum() >= 3:
            rank_col = c
            break
    if rank_col is None:
        return pd.DataFrame()

    # pidä vain tulosrivit
    t = t[t[rank_col].astype(str).str.contains(r"^\s*\d{1,3}\.", regex=True, na=False)].copy()

    out = pd.DataFrame()
    out["rank"] = t[rank_col].astype(str).str.extract(r"^\s*(\d{1,3})\.")[0].astype(int)
    out["player"] = t[rank_col].astype(str).str.replace(r"^\s*\d{1,3}\.\s*", "", regex=True).str.strip()
    out["competition"] = comp_id
    out["source"] = url
    return out[["player","rank","competition","source"]]

