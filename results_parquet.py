def parse_competition(comp_id: int) -> pd.DataFrame:
    """
    Hakee yhden kisan /{id}/tulokset/keskeneraiset.php
    Palauttaa rivit: player, rank, avg, source, competition
    """
    url = f"https://www.mrs.fi/{comp_id}/tulokset/keskeneraiset.php"
    html = fetch_html(url)

    tables = pd.read_html(StringIO(html))
    if len(tables) < 2:
        return pd.DataFrame()

    df = tables[1].copy()
    df.columns = [f"c{i}" for i in range(df.shape[1])]

    # pidetään vain tulosrivit (sun PDF:ssä sama idea) [1](https://evl-my.sharepoint.com/personal/greta_sahlberg_evl_fi/Documents/Microsoft%20Copilot%20Chat%20-tiedostot/pelaaja%20tilastoja.pdf)
    df = df[df["c1"].astype(str).str.contains(r"\d{3}\.", na=False)]
    if df.empty:
        return pd.DataFrame()

    out = pd.DataFrame()
    out["rank"] = df["c1"].str.extract(r"(\d+)\.").astype(int)
    out["player"] = df["c1"].str.replace(r"^\d+\.\s*", "", regex=True).str.strip()

    # avg on joskus muotoa "22.20 2." -> poimi ensimmäinen float
    out["avg"] = df.get("c5", pd.Series([None]*len(df))).astype(str).str.extract(r"(\d+\.\d+)")[0]
    out["avg"] = pd.to_numeric(out["avg"], errors="coerce")

    out["source"] = url
    out["competition"] = comp_id
    return out[["player", "rank", "avg", "source", "competition"]]

