def build_dataset(start=2401, end=2622, step=1, max_fail=500) -> pd.DataFrame:
    rows = []
    failed = 0
    ok = 0

    for comp_id in range(start, end, step):
        try:
            df = parse_competition(comp_id)
            if not df.empty:
                rows.append(df)
                ok += 1
            else:
                failed += 1
        except Exception:
            failed += 1

        if failed > max_fail:
            print("Liikaa epäonnistuneita -> stop. Nosta max_fail jos haluat.")
            break

    if not rows:
        return pd.DataFrame()

    master = pd.concat(rows, ignore_index=True)
    return master

