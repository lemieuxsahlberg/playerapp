def smart_match(query: str):
    q = (query or "").strip()
    if not q:
        return None

    qn = norm_name(q)

    # 1) exact match normalisoituna
    for n in all_names:
        if norm_name(n) == qn:
            return n

    # 2) substring match (sukunimi riittää)
    hits = [n for n in all_names if qn in norm_name(n)]
    if len(hits) >= 1:
        return hits[0]  # palautetaan ensimmäinen osuma (UI:ssa voidaan näyttää myös vaihtoehdot)

    # 3) fuzzy fallback (toleranssi alas)
    matches = get_close_matches(q, all_names, n=1, cutoff=0.2)
    return matches[0] if matches else None

