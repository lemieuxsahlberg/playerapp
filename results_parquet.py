def add_performance(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()

    # field size = suurin rank kyseisessä kisassa (sun PDF:ssä tämä korjasi scoret) [1](https://evl-my.sharepoint.com/personal/greta_sahlberg_evl_fi/Documents/Microsoft%20Copilot%20Chat%20-tiedostot/pelaaja%20tilastoja.pdf)
    field_sizes = df.groupby("competition")["rank"].max().reset_index(name="field_size")
    df = df.merge(field_sizes, on="competition", how="left")

    # performance_score: 1 = voitto, 0 = viimeinen
    df["performance_score"] = 1 - ((df["rank"] - 1) / (df["field_size"] - 1))
    df["performance_score"] = df["performance_score"].fillna(1.0)

    return df

def player_summary(df: pd.DataFrame, players=None) -> pd.DataFrame:
    df = add_performance(df)

    df["player_norm"] = df["player"].apply(norm_name)

    if players:
        wanted = set(norm_name(p) for p in players)
        df = df[df["player_norm"].isin(wanted)].copy()

    # Top5
    top5 = (df[df["rank"] <= 5]
            .groupby("player_norm").size().reset_index(name="top5_finishes"))

    total = df.groupby("player_norm").size().reset_index(name="starts")

    base = total.merge(top5, on="player_norm", how="left").fillna({"top5_finishes": 0})
    base["top5_rate"] = base["top5_finishes"] / base["starts"]

    # per-player perf aggregates
    agg = (df.groupby("player_norm")
           .agg(
               player=("player", "first"),
               tournaments=("competition", "count"),
               avg_rank=("rank", "mean"),
               best_rank=("rank", "min"),
               avg_perf=("performance_score", "mean"),
               std_perf=("performance_score", "std"),
           ).reset_index())

    agg["consistency"] = (1 - agg["std_perf"]).fillna(0)

    # trend + current form (last 5)
    trends = []
    for pn, sub in df.sort_values("competition").groupby("player_norm"):
        y = sub["performance_score"].to_numpy()
        if len(y) >= 3:
            x = np.arange(len(y))
            slope = linregress(x, y).slope
        else:
            slope = 0.0
        current_form = y[-5:].mean() if len(y) else np.nan
        trends.append((pn, slope, current_form))

    trend_df = pd.DataFrame(trends, columns=["player_norm", "trend_slope", "current_form"])

    out = agg.merge(base, on="player_norm", how="left").merge(trend_df, on="player_norm", how="left")

    # “Selection score” (voit säätää painoja)
    out["score"] = (
        0.45 * out["avg_perf"] +
        0.20 * out["top5_rate"] +
        0.20 * out["consistency"] +
        0.15 * out["trend_slope"]
    )

    out = out.sort_values("score", ascending=False)
    return out[["player", "tournaments", "avg_rank", "best_rank", "avg_perf",
                "top5_rate", "consistency", "trend_slope", "current_form", "score"]]

