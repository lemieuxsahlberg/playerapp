        if combined_cell is not None:
            m = re.match(r"^\s*(\d{1,3})\.\s*(.*)", combined_cell)
            if not m:
                continue

            displayed_rank = int(m.group(1))
            player = m.group(2).strip()

            # virallinen sijoitus = viimeinen solu, jos se on kokonaisluku
            last_cell = cells[-1]
